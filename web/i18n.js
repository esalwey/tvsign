function t(key, vars) {
  const entry = I18N[key];
  if (!entry) return key;
  let s = entry[LANG === "fr" ? 0 : 1] ?? entry[1];
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
  return s;
}
